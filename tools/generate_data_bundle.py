#!/usr/bin/env python3
"""Bundle data/*.json into data/bundle.js.

Browsers block fetch() of local JSON files when a page is opened via file://
(double-click). Loading data from a <script> tag works everywhere, so this
script keeps a generated JS copy of the JSON content for that case.

Edit data/*.json, then run: python3 tools/generate_data_bundle.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = {
    'products': 'products.json',
    'categories': 'categories.json',
    'testimonials': 'testimonials.json',
    'posts': 'blog.json',
}


def main():
    data = {}
    for key, filename in FILES.items():
        with (ROOT / 'data' / filename).open(encoding='utf-8') as handle:
            data[key] = json.load(handle)

    payload = json.dumps(data, ensure_ascii=False, indent=2).replace('</', '<\\/')
    output = ROOT / 'data' / 'bundle.js'
    output.write_text(
        '/* Generated by tools/generate_data_bundle.py - do not edit by hand.\n'
        '   Edit data/*.json, then run: python3 tools/generate_data_bundle.py */\n'
        'window.HOMEO_DATA = ' + payload + ';\n',
        encoding='utf-8',
    )
    print('Wrote {} ({} bytes)'.format(output.relative_to(ROOT), output.stat().st_size))


if __name__ == '__main__':
    main()
